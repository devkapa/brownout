use super::cpu::{Cpu, ADDR_SREG};

/// An interrupt source, the reference's `AVRInterruptConfig`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Interrupt {
    /// Vector address in words.
    pub address: u8,
    pub flag_register: u16,
    pub flag_mask: u8,
    pub enable_register: u16,
    pub enable_mask: u8,
    /// Stays pending after it is taken (level-triggered sources).
    pub constant: bool,
    /// The flag bit is active low.
    pub inverse_flag: bool,
}

/// `avrInterrupt`: pushes PC (two bytes, three on a 22-bit PC), clears the
/// global interrupt flag, takes two cycles and jumps to the vector. The
/// reference does not add the usual extra cycle, and PC is the already
/// incremented address of the next instruction.
pub fn avr_interrupt(cpu: &mut Cpu, addr: u8) {
    let sp = cpu.sp() as i32;
    let pc = cpu.pc;
    cpu.wr(sp, (pc & 0xff) as u8);
    cpu.wr(sp - 1, ((pc >> 8) & 0xff) as u8);
    if cpu.pc22_bits {
        cpu.wr(sp - 2, ((pc >> 16) & 0xff) as u8);
    }
    cpu.set_sp((sp - if cpu.pc22_bits { 3 } else { 2 }) as u16);
    cpu.data[ADDR_SREG] &= 0x7f;
    cpu.cycles += 2;
    cpu.pc = addr as i32;
}

// ---- W2a: heap bytes (generated by core/scripts/gen_heap_bytes.py; regenerate, do not edit) ----

impl crate::snapshot::HeapBytes for Interrupt {
    #[allow(unused_mut, unused_variables)]
    fn heap_bytes(&self, w: &mut crate::snapshot::Walk) -> usize {
        let mut n = 0;
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.address, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.flag_register, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.flag_mask, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.enable_register, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.enable_mask, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.constant, w); }
        { n += crate::snapshot::HeapBytes::heap_bytes(&self.inverse_flag, w); }
        n
    }
}
