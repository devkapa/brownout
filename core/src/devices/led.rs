    #[test]
    fn current_is_bounded_below_by_negative_is() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        // Mildly reverse-biased: exp(v/vtn) has not yet underflowed to exactly
        // 0, so I(v) sits strictly between -Is and 0, approaching -Is as v
        // becomes more negative (section A "Currents": "at least -Is").
        let i = law.current(-1.0);
        assert!(i > -law.is && i < 0.0, "reverse current {i} should be in (-Is, 0) with -Is={}", -law.is);
        // Deeply reverse-biased: exp underflows to exactly 0.0, so I(v)
        // saturates at exactly -Is (never below it).
        let deep = law.current(-50.0);
        assert_eq!(deep, -law.is);
    }

    #[test]
    fn current_follows_the_tangent_past_vsat() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        let at_vsat = law.current(law.vsat);
        let past = law.current(law.vsat + 1.0);
        let (g, _) = law.companion(law.vsat + 1.0);
        // The tangent's slope is gd (without GMIN); past - at_vsat should be
        // gd * 1.0 to within a small numerical tolerance.
        let gd = g - GMIN_D;
        assert!((past - at_vsat - gd).abs() < 1e-6, "past={past}, at_vsat={at_vsat}, gd={gd}");
    }

    #[test]
    fn companion_g_includes_gmin_and_ieq_reconstructs_current_at_vprev() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        let v_prev = 1.7;
        let (g, ieq) = law.companion(v_prev);
        let id = law.current(v_prev);
        assert!((g * v_prev + ieq - id).abs() < 1e-9, "g*v+ieq should reconstruct I(vPrev): {} vs {}", g * v_prev + ieq, id);
        assert!(g > GMIN_D);
    }

