    #[test]
    fn bicolor_readout_is_the_unclamped_max_and_can_go_slightly_negative() {
        let d = bicolor_device(vec![pin(0), pin(1), pin(2)], vec![1.8, 2.0, 0.02, 0.02, 0.0]);
        let js = junctions(0, &d, 25.0);
        // a1 forward-biased strongly, a2 reverse-biased: max should be a1's
        // current (positive), channel[1] floored at 0 while element_i is not
        // floored for a1 (still governed by a1 since it's the max).
        let voltages = [2.5, -5.0, 0.0]; // a1=2.5V, a2=-5V, k=0V
        let mut element_i = 0.0;
        let mut channels = [0.0; 2];
        readout(&d, &js, &voltages, false, &mut element_i, &mut channels);
        assert!(element_i > 0.0);
        assert_eq!(channels[1], 0.0, "reverse-biased a2 channel floors at 0");
        assert!(channels[0] > 0.0);

        // Now both reverse-biased: element_i (the raw max, unclamped) must be
        // allowed to go slightly negative, while both channels stay at 0.
        let voltages_rev = [-1.0, -2.0, 0.0];
        readout(&d, &js, &voltages_rev, false, &mut element_i, &mut channels);
        assert!(element_i < 0.0, "unclamped max of two reverse currents should be negative: {element_i}");
        assert_eq!(channels, [0.0, 0.0]);
    }

