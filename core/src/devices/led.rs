//! LED junctions (core/README.md, "Kernel semantics: LEDs and displays
//! (W1e)"). Owned by W1e worker E2a. Pure functions: no solver state.
//!
//! The public API below is the orchestrator's lock, declared before dispatch
//! so no worker needs to touch `devices/mod.rs`: nothing in the solver calls
//! these yet (E2b wires them into `partition.rs`/`solve/*.rs` after this
//! lands). `junctions` and `readout` cover all five kinds and hand codes 33
//! and 34 to [`super::seg7`].
//!
//! The junction law's helper functions below (`thermal_voltage` and friends)
//! mirror classic's own exported functions of the same math (SE:156-193):
//! `thermalVoltage`, `junctionForwardVoltage`, `saturationCurrentAtTemperature`
//! (`src/sim/engine/sim-engine.ts`) and `shockleyIsFromVf`,
//! `shockleyDiodeCurrent`, `stampDiodeShockley` (`src/sim/engine/elements.ts`).
//! Rust's `f64::exp`/`powf` need not match V8's `Math.exp`/`Math.pow` to the
//! last bit (LEDs point 2, D13); `led_golden.rs` (generated by
//! `scripts/gen-led-golden.ts` from classic's own functions, replayed
//! through this module's `JunctionLaw`) pins the two within 4 ulp.

use crate::kinds::{self, bicolor_param, led_param, rgb_param};
use crate::program::{Device, PIN_FLAG_OPEN};

/// Boltzmann constant over electron charge, V/K (classic's `K_B_OVER_Q`,
/// SE:109).
const K_B_OVER_Q: f64 = 8.617_333_262_145e-5;
/// The catalog's reference temperature, °C (classic's `NOMINAL_TEMP_C`).
const NOMINAL_TEMP_C: f64 = 25.0;
/// V/°C, classic's `DEFAULT_VF_TEMPCO` (SE:111). Fixed: no param overrides it
/// (LEDs point 3).
const DEFAULT_VF_TEMPCO: f64 = -0.002;
/// `n` for every kind but `led`, which reads its own param instead (LEDs
/// point 2). `led` alone stores `n` as a param because it alone can differ
/// from classic's `N_LED` default.
pub(crate) const N_LED: f64 = 2.0;

/// The numerical shunt every junction's companion conductance carries (LEDs
/// point 2, classic's `GMIN_D`). `pub` so E2b's source KCL fold (LEDs point
/// 12: "`I(vA - vK) + GMIN_D * (vA - vK)`") shares this exact literal rather
/// than a second copy of `1e-12`.
pub const GMIN_D: f64 = 1e-12;

/// Classic's `thermalVoltage` (SE:156-159): `kT/q` at `t_c` °C.
fn thermal_voltage(t_c: f64) -> f64 {
    K_B_OVER_Q * (t_c + 273.15).max(1.0)
}

/// Classic's `junctionForwardVoltage` (SE:162-168): the catalog `Vf` at 25 °C,
/// linearly de-rated by the fixed tempco, floored at 50 mV.
fn junction_forward_voltage(vf_at_25c: f64, t_c: f64) -> f64 {
    (vf_at_25c + DEFAULT_VF_TEMPCO * (t_c - NOMINAL_TEMP_C)).max(0.05)
}

/// Classic's `saturationCurrentAtTemperature` (SE:175-193): the `led` `Is`
/// override's own temperature scaling, SPICE's silicon-bandgap law. `emission`
/// is the junction's own `n` (not yet floored — that happens here, exactly
/// as classic's local `nn` does, and nowhere else).
fn saturation_current_at_temperature(is_at_25c: f64, t_c: f64, emission: f64) -> f64 {
    let t_nom = NOMINAL_TEMP_C + 273.15;
    let t = (t_c + 273.15).max(1.0);
    let n = emission.max(0.1);
    let silicon_bandgap_ev = 1.11;
    let xti = 3.0;
    let exponent = ((silicon_bandgap_ev / (n * K_B_OVER_Q)) * (1.0 / t_nom - 1.0 / t)).min(80.0).max(-80.0);
    (is_at_25c * (t / t_nom).powf(xti / n) * exponent.exp()).min(1.0).max(1e-30)
}

/// One junction's law at one temperature (LEDs point 2). Takes `t_c` so W1g
/// can feed a held junction temperature without a signature change.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct JunctionLaw {
    pub vtn: f64,
    pub is: f64,
    pub vsat: f64,
}

impl JunctionLaw {
    /// `is_override` is a `led`'s `Is` param when `isSet = 1`; every other
    /// kind always passes `None` (LEDs point 2: "`n` and the `Is` override
    /// exist only on `led`").
    pub fn at(vf25: f64, i_rated: f64, n: f64, is_override: Option<f64>, t_c: f64) -> JunctionLaw {
        let vt = thermal_voltage(t_c);
        let vf = junction_forward_voltage(vf25, t_c);
        let vtn = n * vt;
        let is = match is_override {
            Some(is25) => saturation_current_at_temperature(is25, t_c, n),
            None => i_rated * (-vf / vtn).exp(),
        };
        let vsat = (40.0 * vtn).max(vf + 5.0 * vtn).min(80.0 * vtn);
        JunctionLaw { vtn, is, vsat }
    }

    /// `I(v)`, anode to cathode, GMIN excluded: the exponential below
    /// `vsat`, its tangent above (classic's `shockleyDiodeCurrent`,
    /// EL:772-786).
    pub fn current(&self, v: f64) -> f64 {
        let c = v.min(self.vsat);
        let e = (c / self.vtn).exp();
        self.is * (e - 1.0) + ((self.is * e) / self.vtn) * (v - self.vsat).max(0.0)
    }

    /// `(g, ieq)` about `v_prev`: `g` includes [`GMIN_D`], `ieq` does not
    /// (classic's `stampDiodeShockley`, EL:693-742). The branch current
    /// anode to cathode is `g * (vA - vK) + ieq`.
    pub fn companion(&self, v_prev: f64) -> (f64, f64) {
        let v = if v_prev > self.vsat { self.vsat } else { v_prev };
        let e = (v / self.vtn).exp();
        let gd = (self.is * e) / self.vtn;
        let id = self.current(v_prev);
        let g = gd + GMIN_D;
        let ieq = id - gd * v_prev;
        (g, ieq)
    }
}

/// One junction of one device (LEDs point 1). Listed even when self-shorted,
/// so the device's channel indexing stays fixed; such a junction stamps
/// nothing.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Junction {
    /// The owning device's record index.
    pub device: usize,
    /// The device's channel for this junction (0 for a `led`, which has no
    /// channel slots).
    pub channel: usize,
    /// The junction's anode NODE (not a device-pin index: LEDs point 4 —
    /// "the solver places and stamps them by node").
    pub anode: usize,
    /// The junction's cathode node.
    pub cathode: usize,
    pub law: JunctionLaw,
}

impl Junction {
    /// LEDs point 1: a junction whose two pins share a node stamps nothing
    /// and does not classify.
    pub fn stamped(&self) -> bool {
        self.anode != self.cathode
    }
}

pub(crate) fn is_open(device: &Device, pin_index: usize) -> bool {
    device.pins[pin_index].flags & PIN_FLAG_OPEN != 0
}

/// A plain `led`'s law at `t_c` from its resolved params (LEDs point 2). One
/// body for the load-time law in [`junctions`] and W1g's held-temperature law
/// in [`led_law_at`], so the two cannot drift apart.
fn led_law(params: &[f64], t_c: f64) -> JunctionLaw {
    let is_override = if params[led_param::IS_SET] != 0.0 { Some(params[led_param::IS]) } else { None };
    JunctionLaw::at(params[led_param::VF], params[led_param::I_RATED], params[led_param::N], is_override, t_c)
}

/// The law of a plain `led` at a held junction temperature `t_c` (W1g point 4:
/// `vt`, `vf(T)`, `Is(T)` and `vSat` all at `T_hold`). `None` for any other
/// kind: only a plain `led` with a thermal identity couples, and every other
/// junction stays at `AMBIENT_C` (LEDs point 3). At `t_c = AMBIENT_C` this is
/// the law [`junctions`] builds, bit for bit.
pub fn led_law_at(device: &Device, t_c: f64) -> Option<JunctionLaw> {
    (device.kind == kinds::LED).then(|| led_law(&device.params, t_c))
}

/// The junctions of one LED-family device, fixed at load, at `ambient_c`
/// (LEDs points 1 and 3). Empty for a `burnt` device.
pub fn junctions(device_index: usize, device: &Device, ambient_c: f64) -> Vec<Junction> {
    match device.kind {
        kinds::LED => {
            let p = &device.params;
            if p[led_param::BURNT] != 0.0 {
                return Vec::new();
            }
            let law = led_law(p, ambient_c);
            vec![Junction { device: device_index, channel: 0, anode: device.pins[0].node, cathode: device.pins[1].node, law }]
        }
        kinds::RGB_LED => {
            let p = &device.params;
            if p[rgb_param::BURNT] != 0.0 {
                return Vec::new();
            }
            // Pins by id, record-layout table: r_a(0), g_a(1), b_a(2), com_k(3).
            let com_k = device.pins[3].node;
            [(0usize, rgb_param::VF_R), (1, rgb_param::VF_G), (2, rgb_param::VF_B)]
                .into_iter()
                .map(|(channel, vf_idx)| {
                    let law = JunctionLaw::at(p[vf_idx], p[rgb_param::I_RATED], N_LED, None, ambient_c);
                    Junction { device: device_index, channel, anode: device.pins[channel].node, cathode: com_k, law }
                })
                .collect()
        }
        kinds::BICOLOR_LED => {
            let p = &device.params;
            if p[bicolor_param::BURNT] != 0.0 {
                return Vec::new();
            }
            // Pins by id, record-layout table: a1(0), a2(1), k(2).
            let k = device.pins[2].node;
            [(0usize, bicolor_param::VF1), (1, bicolor_param::VF2)]
                .into_iter()
                .map(|(channel, vf_idx)| {
                    let law = JunctionLaw::at(p[vf_idx], p[bicolor_param::I_RATED], N_LED, None, ambient_c);
                    Junction { device: device_index, channel, anode: device.pins[channel].node, cathode: k, law }
                })
                .collect()
        }
        kinds::SEG7_CC | kinds::SEG7_CA => super::seg7::junctions(device_index, device, ambient_c),
        _ => Vec::new(),
    }
}

/// The device's `elementI` and channel values from the published voltages
/// ("Currents"; LEDs point 13). `failed` is W1g's `led_failed` latch and takes
/// the same path as `burnt`: `elementI` 0 and, for an `rgb_led` or
/// `bicolor_led`, `NaN` channels, meaning absent (W1g point 12). A `seg7` has no
/// failure surface (Q-O22) and ignores it. `voltages` is the whole circuit's
/// node-voltage array (`Junction.anode`/`cathode` index into it directly).
pub fn readout(device: &Device, junctions: &[Junction], voltages: &[f64], failed: bool, element_i: &mut f64, channels: &mut [f64]) {
    match device.kind {
        kinds::LED => {
            let absent = failed || device.params[led_param::BURNT] != 0.0;
            *element_i = if absent {
                0.0
            } else {
                junctions.first().map_or(0.0, |j| j.law.current(voltages[j.anode] - voltages[j.cathode]))
            };
        }
        kinds::RGB_LED => {
            let absent = failed || device.params[rgb_param::BURNT] != 0.0;
            if absent {
                *element_i = 0.0;
                channels.iter_mut().for_each(|c| *c = f64::NAN);
                return;
            }
            channels.iter_mut().for_each(|c| *c = 0.0);
            // "The running maximum starting at 0" (LEDs, section A "Currents"):
            // the floor is 0 even with no junctions (can't happen here short of
            // a malformed record, but matches classic's unconditional
            // `setElementCurrent(comp.id, 0)` before the channel loop).
            let mut max_i = 0.0f64;
            for j in junctions {
                let i = j.law.current(voltages[j.anode] - voltages[j.cathode]);
                if j.channel < channels.len() {
                    channels[j.channel] = i.max(0.0);
                }
                max_i = max_i.max(i);
            }
            *element_i = max_i;
        }
        kinds::BICOLOR_LED => {
            let absent = failed || device.params[bicolor_param::BURNT] != 0.0;
            if absent {
                *element_i = 0.0;
                channels.iter_mut().for_each(|c| *c = f64::NAN);
                return;
            }
            channels.iter_mut().for_each(|c| *c = 0.0);
            // "max(I1, I2) of the unclamped channel currents ... it can go
            // slightly negative" (section A "Currents") — no floor, unlike
            // rgb_led, so the running max starts at the first junction's own
            // current rather than at 0.
            let mut max_i: Option<f64> = None;
            for j in junctions {
                let i = j.law.current(voltages[j.anode] - voltages[j.cathode]);
                if j.channel < channels.len() {
                    channels[j.channel] = i.max(0.0);
                }
                max_i = Some(max_i.map_or(i, |m| m.max(i)));
            }
            *element_i = max_i.unwrap_or(0.0);
        }
        kinds::SEG7_CC | kinds::SEG7_CA => super::seg7::readout(device, junctions, voltages, element_i, channels),
        _ => {}
    }
}

/// The Q-O24 damage limit `ifMax` of an LED-family device (LEDs point 15):
/// `led` param 2 (`iRated`, which for a `led` is the same expression), and the
/// `ifMax` param of an `rgb_led` or `bicolor_led`, which reads specs where the
/// stamp does not. `None` for a `seg7`, which has no damage surface (Q-O22),
/// and for any other kind.
pub fn if_max(device: &Device) -> Option<f64> {
    match device.kind {
        kinds::LED => Some(device.params[led_param::I_RATED]),
        kinds::RGB_LED => Some(device.params[rgb_param::IF_MAX]),
        kinds::BICOLOR_LED => Some(device.params[bicolor_param::IF_MAX]),
        _ => None,
    }
}

/// Classic's `peakI` (SC:482-491) from a device's junction currents in
/// channel order, GMIN excluded: `max(|elementI|, max over |channel|)` with
/// the `elementI` and channel rules of "Currents" and LEDs point 13:
/// - `led`: `|I|`;
/// - `bicolor_led`: `max(|max(I1, I2)|, max(0, I1), max(0, I2))`, so with both
///   channels reverse-biased it is `|max(I1, I2)|`, the smaller saturation
///   current;
/// - `rgb_led`: `max(0, Ir, Ig, Ib)`.
///
/// `0` for any other kind. A channel the slice lacks counts as no current.
pub fn peak_from_currents(kind: u32, currents: &[f64]) -> f64 {
    let at = |i: usize| currents.get(i).copied().unwrap_or(0.0);
    match kind {
        kinds::LED => at(0).abs(),
        kinds::BICOLOR_LED => {
            let element = at(0).max(at(1));
            element.abs().max(at(0).max(0.0).abs()).max(at(1).max(0.0).abs())
        }
        kinds::RGB_LED => {
            // `elementI` starts its running maximum at 0, and every channel is
            // `max(0, I)`, so each `|.|` is the value itself.
            let element = 0.0f64.max(at(0)).max(at(1)).max(at(2));
            element.abs()
        }
        _ => 0.0,
    }
}

/// `peakI` of a device at the published `voltages`, from its own junction
/// currents with each junction's current law (the held temperature's, for an
/// identified `led`), and `0` for a `burnt` device, which stamps nothing so its
/// stress only bleeds. A latched device does nothing afterwards (point 5), so
/// the caller does not ask. `voltages` is the whole circuit's node-voltage
/// array.
pub fn peak_current(device: &Device, junctions: &[Junction], voltages: &[f64]) -> f64 {
    peak_current_with(device, junctions, |n| voltages[n])
}

/// [`peak_current`] with the node voltages read through `v` (ruling R90
/// (a)'s stepped stress probe reads a trial's own nodes).
pub fn peak_current_with(device: &Device, junctions: &[Junction], v: impl Fn(usize) -> f64) -> f64 {
    let burnt = match device.kind {
        kinds::LED => device.params[led_param::BURNT],
        kinds::RGB_LED => device.params[rgb_param::BURNT],
        kinds::BICOLOR_LED => device.params[bicolor_param::BURNT],
        _ => return 0.0,
    };
    if burnt != 0.0 {
        return 0.0;
    }
    let mut currents = [0.0f64; 3];
    for j in junctions {
        if j.channel < currents.len() {
            currents[j.channel] = j.law.current(v(j.anode) - v(j.cathode));
        }
    }
    peak_from_currents(device.kind, &currents)
}

