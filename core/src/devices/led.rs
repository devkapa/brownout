    // ---- ulp comparison, for the golden replay ----------------------------

    fn ulp_key(v: f64) -> i64 {
        let bits = v.to_bits() as i64;
        if bits < 0 {
            i64::MIN.wrapping_sub(bits)
        } else {
            bits
        }
    }

    fn ulp_diff(a: f64, b: f64) -> u64 {
        let ka = ulp_key(a) as i128;
        let kb = ulp_key(b) as i128;
        (ka - kb).unsigned_abs() as u64
    }

    fn assert_within_ulp(got: f64, want: f64, max_ulp: u64, label: &str) {
        assert_eq!(got.is_finite(), want.is_finite(), "{label}: got {got}, want {want} (finiteness differs)");
        if !got.is_finite() {
            assert!(got.is_nan() && want.is_nan() || got == want, "{label}: got {got}, want {want}");
            return;
        }
        let diff = ulp_diff(got, want);
        assert!(diff <= max_ulp, "{label}: got {got}, want {want}, {diff} ulp apart (max {max_ulp})");
    }

    #[test]
    fn golden_matches_classics_junction_law_within_4_ulp() {
        assert!(!led_golden::GOLDEN_ROWS.is_empty(), "the generator must have run at least once");
        let mut worst = 0u64;
        for &(vf25, i_rated, n, is_set, is_value, t_c, v, vtn, is, vsat, current, g, ieq) in led_golden::GOLDEN_ROWS {
            let is_override = if is_set != 0.0 { Some(is_value) } else { None };
            let law = JunctionLaw::at(vf25, i_rated, n, is_override, t_c);
            assert_within_ulp(law.vtn, vtn, 4, "vtn");
            assert_within_ulp(law.is, is, 4, "is");
            assert_within_ulp(law.vsat, vsat, 4, "vsat");
            worst = worst.max(ulp_diff(law.vtn, vtn)).max(ulp_diff(law.is, is)).max(ulp_diff(law.vsat, vsat));

            let got_current = law.current(v);
            assert_within_ulp(got_current, current, 4, "current");
            worst = worst.max(ulp_diff(got_current, current));

            let (got_g, got_ieq) = law.companion(v);
            assert_within_ulp(got_g, g, 4, "g");
            assert_within_ulp(got_ieq, ieq, 4, "ieq");
            worst = worst.max(ulp_diff(got_g, g)).max(ulp_diff(got_ieq, ieq));
        }
        // Not a hard assertion (the loop above already enforces 4 ulp on
        // every field): printed with `--nocapture` for the worker's report.
        println!("led golden: {} rows, worst ulp {worst}", led_golden::GOLDEN_ROWS.len());
    }

    // ---- JunctionLaw::at / current / companion, hand-picked cases ---------

    #[test]
    fn vsat_clamps_at_80_vtn_when_vf_is_far_above_it() {
        // vf25 = 5.0, n = 1, T = 25: 80*vtn ~= 2.06 V, well under vf, so vSat
        // must clamp at 80*vtn rather than vf + 5*vtn (LEDs point 2; F4-style
        // high-Vf part).
        let law = JunctionLaw::at(5.0, 0.02, 1.0, None, 25.0);
        let vt = thermal_voltage(25.0);
        assert!((law.vsat - 80.0 * vt).abs() < 1e-12, "vsat={}, 80vtn={}", law.vsat, 80.0 * vt);
    }

    #[test]
    fn vf_floors_at_50_mv() {
        // A tiny vf25 driven further negative by the tempco at a high T must
        // floor at 50 mV rather than go negative (LEDs point 2).
        assert_eq!(junction_forward_voltage(0.05, 125.0), 0.05);
        assert_eq!(junction_forward_voltage(0.01, 125.0), 0.05);
        assert_eq!(junction_forward_voltage(1.8, 25.0), 1.8, "no tempco shift at the nominal temperature");
    }

    #[test]
    fn current_is_bounded_below_by_negative_is() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        // Mildly reverse-biased: exp(v/vtn) has not yet underflowed to exactly
        // 0, so I(v) sits strictly between -Is and 0, approaching -Is as v
        // becomes more negative (section A "Currents": "at least -Is").
        let i = law.current(-1.0);
        assert!(i > -law.is && i < 0.0, "reverse current {i} should be in (-Is, 0) with -Is={}", -law.is);
        // Deeply reverse-biased: exp underflows to exactly 0.0, so I(v)
        // saturates at exactly -Is (never below it).
        let deep = law.current(-50.0);
        assert_eq!(deep, -law.is);
    }

    #[test]
    fn current_follows_the_tangent_past_vsat() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        let at_vsat = law.current(law.vsat);
        let past = law.current(law.vsat + 1.0);
        let (g, _) = law.companion(law.vsat + 1.0);
        // The tangent's slope is gd (without GMIN); past - at_vsat should be
        // gd * 1.0 to within a small numerical tolerance.
        let gd = g - GMIN_D;
        assert!((past - at_vsat - gd).abs() < 1e-6, "past={past}, at_vsat={at_vsat}, gd={gd}");
    }

    #[test]
    fn companion_g_includes_gmin_and_ieq_reconstructs_current_at_vprev() {
        let law = JunctionLaw::at(1.8, 0.02, 2.0, None, 25.0);
        let v_prev = 1.7;
        let (g, ieq) = law.companion(v_prev);
        let id = law.current(v_prev);
        assert!((g * v_prev + ieq - id).abs() < 1e-9, "g*v+ieq should reconstruct I(vPrev): {} vs {}", g * v_prev + ieq, id);
        assert!(g > GMIN_D);
    }

    #[test]
