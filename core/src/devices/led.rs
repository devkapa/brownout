    // ---- ulp comparison, for the golden replay ----------------------------

    fn ulp_key(v: f64) -> i64 {
        let bits = v.to_bits() as i64;
        if bits < 0 {
            i64::MIN.wrapping_sub(bits)
        } else {
            bits
        }
    }

    fn ulp_diff(a: f64, b: f64) -> u64 {
        let ka = ulp_key(a) as i128;
        let kb = ulp_key(b) as i128;
        (ka - kb).unsigned_abs() as u64
    }

    fn assert_within_ulp(got: f64, want: f64, max_ulp: u64, label: &str) {
        assert_eq!(got.is_finite(), want.is_finite(), "{label}: got {got}, want {want} (finiteness differs)");
        if !got.is_finite() {
            assert!(got.is_nan() && want.is_nan() || got == want, "{label}: got {got}, want {want}");
            return;
        }
        let diff = ulp_diff(got, want);
        assert!(diff <= max_ulp, "{label}: got {got}, want {want}, {diff} ulp apart (max {max_ulp})");
    }

    #[test]
    fn golden_matches_classics_junction_law_within_4_ulp() {
        assert!(!led_golden::GOLDEN_ROWS.is_empty(), "the generator must have run at least once");
        let mut worst = 0u64;
        for &(vf25, i_rated, n, is_set, is_value, t_c, v, vtn, is, vsat, current, g, ieq) in led_golden::GOLDEN_ROWS {
            let is_override = if is_set != 0.0 { Some(is_value) } else { None };
            let law = JunctionLaw::at(vf25, i_rated, n, is_override, t_c);
            assert_within_ulp(law.vtn, vtn, 4, "vtn");
            assert_within_ulp(law.is, is, 4, "is");
            assert_within_ulp(law.vsat, vsat, 4, "vsat");
            worst = worst.max(ulp_diff(law.vtn, vtn)).max(ulp_diff(law.is, is)).max(ulp_diff(law.vsat, vsat));

            let got_current = law.current(v);
            assert_within_ulp(got_current, current, 4, "current");
            worst = worst.max(ulp_diff(got_current, current));

            let (got_g, got_ieq) = law.companion(v);
            assert_within_ulp(got_g, g, 4, "g");
            assert_within_ulp(got_ieq, ieq, 4, "ieq");
            worst = worst.max(ulp_diff(got_g, g)).max(ulp_diff(got_ieq, ieq));
        }
        // Not a hard assertion (the loop above already enforces 4 ulp on
        // every field): printed with `--nocapture` for the worker's report.
        println!("led golden: {} rows, worst ulp {worst}", led_golden::GOLDEN_ROWS.len());
    }

