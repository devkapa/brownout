"""Generates the HeapBytes impls for every Clone struct and enum in core/src
(W2a: `bo_engine_snapshot_bytes`'s walk, core/src/snapshot.rs).

Usage, from core/:
  python3 scripts/gen_heap_bytes.py src --write   regenerate
  python3 scripts/gen_heap_bytes.py src --check   exit 1 if any section is stale

Each file holding Clone types gets a marked section at its end (so the impls
can read private fields), replaced on every run. Run it after adding or
changing a field of an engine type; `the_walk_counts_what_a_copy_allocates`
catches a stale section only on the boards it runs.
"""
import os, re, sys

SRC = sys.argv[1]
WRITE = '--write' in sys.argv
CHECK = '--check' in sys.argv
stale = []
BEGIN = '// ---- W2a: heap bytes (generated by core/scripts/gen_heap_bytes.py; regenerate, do not edit) ----'
OLD_BEGIN = '// ---- W2a: heap bytes (generated by the size walk generator; regenerate, do not edit) ----'
SKIP_FILES = ('_tests.rs', '_golden.rs', 'kinds.rs', 'error.rs', 'abi.rs')
EXTRA = {'Family', 'LatchBook'}  # Clone written by hand
SKIP_NAMES = {'Shared', 'GlobalCell', 'Kernel'}  # hand-written


def strip_section(s):
    for b in (BEGIN, OLD_BEGIN):
        i = s.find('\n' + b)
        if i >= 0:
            return s[:i] + '\n'
    return s


def match_brace(s, i, open_c, close_c):
    depth = 0
    j = i
    while j < len(s):
        c = s[j]
        if c == '/' and s[j:j+2] == '//':
            j = s.index('\n', j)
            continue
        if c == '"':
            j += 1
            while s[j] != '"':
                j += 2 if s[j] == '\\' else 1
        elif c == open_c:
            depth += 1
        elif c == close_c:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    raise ValueError('unbalanced')


def split_top(body):
    """Split at depth-0 commas, ignoring // comments."""
    out, depth, cur, j = [], 0, '', 0
    while j < len(body):
        c = body[j]
        if body[j:j+2] == '//':
            k = body.find('\n', j)
            k = len(body) if k < 0 else k
            cur += body[j:k]
            j = k
            continue
        if c in '<([{':
            depth += 1
        elif c in '>)]}':
            # `->` is not a closing angle
            if not (c == '>' and j > 0 and body[j-1] == '-'):
                depth -= 1
        if c == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
        j += 1
    if cur.strip():
        out.append(cur)
    return out


def attrs_and_rest(chunk):
    """Leading attributes (cfg ones kept) and the rest, comments dropped."""
    lines = [l.strip() for l in chunk.strip().split('\n')]
    cfgs, rest = [], []
    for l in lines:
        if l.startswith('//'):
            continue
        if l.startswith('#[') and not rest:
            if l.startswith('#[cfg('):
                cfgs.append(l)
            continue
        rest.append(l)
    return cfgs, ' '.join(rest).strip()


def named_fields(body):
    fields = []
    for chunk in split_top(body):
        cfgs, rest = attrs_and_rest(chunk)
        if not rest:
            continue
        m = re.match(r'(?:pub(?:\([^)]*\))?\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*:', rest)
        if not m:
            raise ValueError(f'field? {rest!r}')
        fields.append((cfgs, m.group(1)))
    return fields


def term(cfgs, expr):
    c = ''.join(f'{a} ' for a in cfgs)
    return f'        {c}{{ n += {expr}; }}\n'


def gen_struct(name, generics, kind, body):
    gp = generics or ''
    impl_g = gp
    bounds = ''
    if gp:
        params = [p.split(':')[0].strip() for p in split_top(gp[1:-1])]
        params = [p for p in params if not p.startswith("'")]
        impl_g = '<' + ', '.join(f'{p}: Clone + crate::snapshot::HeapBytes' for p in params) + '>'
        gp = '<' + ', '.join(params) + '>'
    head = f'impl{impl_g} crate::snapshot::HeapBytes for {name}{gp} {{\n    #[allow(unused_mut, unused_variables)]\n    fn heap_bytes(&self, w: &mut crate::snapshot::Walk) -> usize {{\n        let mut n = 0;\n'
    tail = '        n\n    }\n}\n'
    out = ''
    if kind == 'named':
        for cfgs, f in named_fields(body):
            out += term(cfgs, f'crate::snapshot::HeapBytes::heap_bytes(&self.{f}, w)')
    elif kind == 'tuple':
        for i, chunk in enumerate(split_top(body)):
            cfgs, rest = attrs_and_rest(chunk)
            if rest:
                out += term(cfgs, f'crate::snapshot::HeapBytes::heap_bytes(&self.{i}, w)')
    return head + out + tail


def gen_enum(name, body):
    arms = ''
    for chunk in split_top(body):
        cfgs, rest = attrs_and_rest(chunk)
        if not rest:
            continue
        rest = rest.split('=')[0].strip() if '(' not in rest and '{' not in rest else rest
        m = re.match(r'([A-Za-z_][A-Za-z0-9_]*)\s*(.*)$', rest, re.S)
        v, tailtxt = m.group(1), m.group(2).strip()
        c = ''.join(f'{a} ' for a in cfgs)
        if tailtxt.startswith('('):
            inner = tailtxt[1:tailtxt.rindex(')')]
            k = len([x for x in split_top(inner) if x.strip()])
            names = [f'f{i}' for i in range(k)]
            sumx = ' + '.join(f'crate::snapshot::HeapBytes::heap_bytes({x}, w)' for x in names) or '0'
            arms += f'            {c}{name}::{v}({", ".join(names)}) => {sumx},\n'
        elif tailtxt.startswith('{'):
            inner = tailtxt[1:tailtxt.rindex('}')]
            fs = [f for _, f in named_fields(inner)]
            sumx = ' + '.join(f'crate::snapshot::HeapBytes::heap_bytes({f}, w)' for f in fs) or '0'
            arms += f'            {c}{name}::{v} {{ {", ".join(fs)} }} => {sumx},\n'
        else:
            arms += f'            {c}{name}::{v} => 0,\n'
    if not arms:
        arms = '            _ => 0,\n'
    return (f'impl crate::snapshot::HeapBytes for {name} {{\n    #[allow(unused_variables)]\n    fn heap_bytes(&self, w: &mut crate::snapshot::Walk) -> usize {{\n'
            f'        match self {{\n{arms}        }}\n    }}\n}}\n')


DEF = re.compile(r'#\[derive\(([^)]*)\)\]\s*(?:(?:#\[[^\n]*\]|///[^\n]*|//[^\n]*)\s*)*(?:pub(?:\([^)]*\))?\s+)?(struct|enum)\s+([A-Za-z_][A-Za-z0-9_]*)(<[^{(;]*?>)?\s*(where[^{]*)?([{(;])')

total = 0
for root, _, files in os.walk(SRC):
    for fn in sorted(files):
        if not fn.endswith('.rs') or fn.endswith(SKIP_FILES):
            continue
        p = os.path.join(root, fn)
        s = strip_section(open(p).read())
        # Only top-level items: skip anything inside `mod tests`
        tests_at = len(s)
        mt = re.search(r'^#\[cfg\(test\)\]\s*\n\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{', s, re.M)
        gens = []
        for m in DEF.finditer(s):
            derives, kind, name, generics, _, opener = m.groups()
            if ('Clone' not in [d.strip() for d in derives.split(',')] and name not in EXTRA) or name in SKIP_NAMES:
                continue
            # inside a cfg(test) module?
            line_start = s.rfind('\n', 0, m.start()) + 1
            if s[line_start] in ' \t':
                continue  # nested (test modules are indented)
            if generics and "'" in generics:
                continue
            # cfg attributes in the item's attribute block (above the derive, or between it and the item)
            k = line_start
            block = s[m.start():m.end()]
            while True:
                prev_end = k - 1
                if prev_end <= 0:
                    break
                prev_start = s.rfind('\n', 0, prev_end) + 1
                line = s[prev_start:prev_end].strip()
                if line.startswith('#[') or line.startswith('///') or line.startswith('//'):
                    block = line + '\n' + block
                    k = prev_start
                    continue
                break
            cfg = ''.join(l.strip() + '\n' for l in block.split('\n') if l.strip().startswith('#[cfg('))
            if opener == ';':
                gens.append(cfg + gen_struct(name, generics, 'unit', ''))
                continue
            i = m.end() - 1
            if opener == '{':
                j = match_brace(s, i, '{', '}')
                body = s[i+1:j]
                gens.append(cfg + (gen_enum(name, body) if kind == 'enum' else gen_struct(name, generics, 'named', body)))
            else:
                j = match_brace(s, i, '(', ')')
                gens.append(cfg + gen_struct(name, generics, 'tuple', s[i+1:j]))
        if gens:
            total += len(gens)
            out = s.rstrip('\n') + '\n\n' + BEGIN + '\n\n' + '\n'.join(gens)
            if WRITE:
                open(p, 'w').write(out)
            if CHECK and open(p).read() != out:
                stale.append(os.path.relpath(p, SRC))
print('total', total)
if CHECK and stale:
    print('stale:', ' '.join(stale))
    sys.exit(1)
